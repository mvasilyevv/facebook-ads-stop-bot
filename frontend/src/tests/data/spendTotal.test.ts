/**
 * Тесты cumulativeSpendTotal — корректная свёртка кумулятивных часовых бакетов
 * chart-data в суммарный спенд (money-bug: наивная сумма задваивала кумулятив).
 */

import { describe, it, expect } from "vitest";
import { cumulativeSpendTotal } from "@/lib/utils/spendTotal";

describe("cumulativeSpendTotal", () => {
  // Один день: бакеты — накопленный итог к концу часа. Итог = ПОСЛЕДНИЙ бакет,
  // а НЕ сумма всех (иначе $1.78 раздулось бы в $5.05 — реальный баг дашборда).
  it("один день: берёт последний кумулятивный бакет, не сумму", () => {
    const buckets = [
      { ts: "2026-06-18T07:00:00+00:00", spend: "0.20" },
      { ts: "2026-06-18T08:00:00+00:00", spend: "0.56" },
      { ts: "2026-06-18T09:00:00+00:00", spend: "1.13" },
      { ts: "2026-06-18T10:00:00+00:00", spend: "1.38" },
      { ts: "2026-06-18T11:00:00+00:00", spend: "1.78" },
    ];
    // Наивная сумма дала бы 5.05 — это и был баг.
    expect(cumulativeSpendTotal(buckets)).toBeCloseTo(1.78, 5);
  });

  // Многодневное окно: спенд сбрасывается посуточно → складываем дневные итоги
  // (последний бакет каждых суток), а не максимум по всему окну.
  it("два дня: суммирует дневные итоги через посуточный сброс", () => {
    const buckets = [
      { ts: "2026-06-17T22:00:00+00:00", spend: "3.00" }, // день 1, последний
      { ts: "2026-06-18T07:00:00+00:00", spend: "0.50" }, // день 2, начало (после сброса)
      { ts: "2026-06-18T11:00:00+00:00", spend: "1.78" }, // день 2, последний
    ];
    expect(cumulativeSpendTotal(buckets)).toBeCloseTo(4.78, 5);
  });

  // Устойчивость к порядку: на каждый день берётся бакет с максимальным ts.
  it("не зависит от порядка входных бакетов", () => {
    const buckets = [
      { ts: "2026-06-18T11:00:00+00:00", spend: "1.78" },
      { ts: "2026-06-18T07:00:00+00:00", spend: "0.20" },
      { ts: "2026-06-18T09:00:00+00:00", spend: "1.13" },
    ];
    expect(cumulativeSpendTotal(buckets)).toBeCloseTo(1.78, 5);
  });

  // Пустой вход и битые ts → 0 без падения.
  it("пустой вход и невалидный ts → 0", () => {
    expect(cumulativeSpendTotal([])).toBe(0);
    expect(cumulativeSpendTotal([{ ts: null, spend: "9.99" }])).toBe(0);
    expect(cumulativeSpendTotal([{ ts: "не-дата", spend: "9.99" }])).toBe(0);
  });

  // spend null/невалидный внутри валидного бакета → трактуется как 0.
  it("null spend в валидном бакете → 0 для этого дня", () => {
    const buckets = [{ ts: "2026-06-18T11:00:00+00:00", spend: null }];
    expect(cumulativeSpendTotal(buckets)).toBe(0);
  });
});
