# -*- coding: utf-8 -*-
"""Разрез плана залива на самостоятельные кампании (issue #214).

Одна кампания плана — один конфиг, одна задача, один наблюдаемый прогон.
До разреза план из N кампаний исполнялся одной задачей: отказ на пятом
объявлении оставлял весь залив в неизвестном исходе, а уже созданные объекты —
сиротами. После разреза падает одна кампания, а остальные остаются
подтверждёнными.

Money-инвариант нумерации: разрез НЕ трогает коды креативов. `code_start`
остаётся полем конфига и проставляется аллокатором на постановке — по одной
кампании за раз, в порядке плана. Сумма диапазонов кампаний равна диапазону
всего плана (`total_code_span`), поэтому коды совпадают с превью.
"""

from __future__ import annotations

from core.campaign_builder.config import CampaignConfig


def campaign_plan_slices(config: CampaignConfig) -> list[CampaignConfig]:
    """План из N кампаний → N конфигов, в каждом ровно одна кампания.

    Порядок сохраняется: он задаёт порядок резервирования диапазонов кодов и
    порядок постановки задач.

    Каждый срез проходит валидацию заново, а не собирается копированием полей:
    именно он попадёт в `campaign_run.config` и будет прочитан воркером как
    самостоятельный конфиг. Срез, который не проходит собственную валидацию,
    обязан быть отвергнут здесь — до создания чего-либо в Meta.
    """
    shared = config.model_dump()
    slices: list[CampaignConfig] = []
    for block in config.campaigns:
        slices.append(CampaignConfig.model_validate({**shared, "campaigns": [block.model_dump()]}))
    return slices


__all__ = ["campaign_plan_slices"]
